"""Make a closed loop route (YAML) for cart_driver.route.

  python3 make_route.py OUT.yaml --rounded-rect XMIN XMAX YMIN YMAX RADIUS [--offset 8.06] [--cw]
  python3 make_route.py OUT.yaml --csv CENTRELINE.csv [--offset 8.06] [--smooth 5]

The route is the centre line shifted ``--offset`` m to the LEFT of the
direction of travel (keep left), resampled every ``--spacing`` m, in the
world frame, describing the front bumper (where the GPS sits).

  --rounded-rect  exact geometry of a loop of straight + curved road segments
                  (tesla_city: -45 105 -105 45 40.5), driven anticlockwise
                  unless --cw
  --csv           a recorded centre line (record_route.py, x,y per row),
                  smoothed with a moving average over --smooth m; use it where
                  the road geometry isn't known. Recordings drift where the
                  centre line is missing (junctions), so prefer the geometry.
"""

import argparse
import csv
import math

import numpy as np


def rounded_rect(xmin, xmax, ymin, ymax, r, spacing):
    """Anticlockwise centre line starting mid top edge, heading -x."""
    corners = [((xmin + r, ymax - r), math.pi / 2), ((xmin + r, ymin + r), math.pi),
               ((xmax - r, ymin + r), -math.pi / 2), ((xmax - r, ymax - r), 0.0)]
    pts = [((xmin + xmax) / 2, ymax)]
    for (cx, cy), a0 in corners:
        start = (cx + r * math.cos(a0), cy + r * math.sin(a0))
        pts += list(np.linspace(pts[-1], start, max(2, int(math.dist(pts[-1], start) / spacing)))[1:])
        n = max(2, int(r * math.pi / 2 / spacing))
        pts += [(cx + r * math.cos(a), cy + r * math.sin(a)) for a in np.linspace(a0, a0 + math.pi / 2, n)[1:]]
    end = pts[0]
    pts += list(np.linspace(pts[-1], end, max(2, int(math.dist(pts[-1], end) / spacing)))[1:-1])
    return np.array(pts)


def resample(pts, spacing):
    """Closed polyline -> points every ``spacing`` m."""
    closed = np.vstack([pts, pts[:1]])
    s = np.r_[0, np.cumsum(np.hypot(*np.diff(closed, axis=0).T))]
    q = np.arange(0, s[-1], s[-1] / round(s[-1] / spacing))
    return np.column_stack([np.interp(q, s, closed[:, 0]), np.interp(q, s, closed[:, 1])])


def smooth(pts, window):
    k = max(1, int(window))
    idx = (np.arange(len(pts))[:, None] + np.arange(-k, k + 1)[None, :]) % len(pts)
    return pts[idx].mean(axis=1)


def offset_left(pts, d):
    tangent = np.roll(pts, -1, axis=0) - np.roll(pts, 1, axis=0)
    tangent /= np.linalg.norm(tangent, axis=1, keepdims=True)
    return pts + d * np.column_stack([-tangent[:, 1], tangent[:, 0]])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out')
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument('--rounded-rect', nargs=5, type=float, metavar=('XMIN', 'XMAX', 'YMIN', 'YMAX', 'R'))
    src.add_argument('--csv')
    ap.add_argument('--cw', action='store_true', help='rounded rect driven clockwise')
    ap.add_argument('--offset', type=float, default=8.06, help='m left of the centre line (kerb-side lane)')
    ap.add_argument('--spacing', type=float, default=0.5)
    ap.add_argument('--smooth', type=float, default=5.0, help='--csv: moving-average half window, m')
    ap.add_argument('--name', default='loop')
    args = ap.parse_args()

    if args.rounded_rect:
        centre = resample(rounded_rect(*args.rounded_rect, spacing=0.1), args.spacing)
        if args.cw:
            centre = centre[::-1]
        source = 'rounded rect ' + ' '.join(f'{v:g}' for v in args.rounded_rect)
    else:
        with open(args.csv) as f:
            raw = np.array([[float(r['x']), float(r['y'])] for r in csv.DictReader(f)])
        centre = resample(raw, args.spacing)
        centre = smooth(centre, args.smooth / args.spacing)
        source = f'recording {args.csv}'
    route = resample(offset_left(centre, args.offset), args.spacing)
    length = float(np.sum(np.hypot(*np.diff(np.vstack([route, route[:1]]), axis=0).T)))

    with open(args.out, 'w') as f:
        f.write(f'# Generated by tools/make_route.py from {source}\n')
        f.write(f'# {args.offset:g} m left of the centre line (keep left), {length:.0f} m, closed.\n')
        f.write(f'name: {args.name}\nframe: world\npoint: front_bumper\nclosed: true\n')
        f.write(f'spacing: {args.spacing}\npoints:\n')
        for x, y in route:
            f.write(f'  - [{x:.3f}, {y:.3f}]\n')
    print(f'{args.out}: {len(route)} points, {length:.1f} m')


if __name__ == '__main__':
    main()
